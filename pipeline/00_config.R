# Поправьте путь ниже на реальное расположение файла на вашем компьютере.
RAW_SAV_PATH   <- "data/raw/survey.sav"
TEXT_VAR       <- "OPEN"   # переменная с высказываниями (открытые ответы)
SEGMENT_VAR    <- "SEGMENT" # переменная сегмента для карты автотегов (map/): число, текст или подписанная SPSS-переменная

# Куда сохраняются промежуточные и итоговые артефакты
DATA_DIR       <- "data"
RDS_RAW        <- file.path(DATA_DIR, "01_raw.rds")
RDS_PREP       <- file.path(DATA_DIR, "02_preprocessed.rds")
W2V_MODEL_PATH <- file.path(DATA_DIR, "03_word2vec.bin")
RDS_APP_DATA   <- file.path(DATA_DIR, "04_app_data.rds")

# Файлы, в которые сохраняются созданные пользователем теги (персистентность)
TAGS_LOG_CSV       <- file.path(DATA_DIR, "tags_log.csv")        # список созданных тегов
STATEMENT_TAGS_CSV <- file.path(DATA_DIR, "statement_tags.csv")  # какому высказыванию какой тег присвоен
BASE_WITH_TAGS_CSV <- file.path(DATA_DIR, "base_with_tags.csv")  # исходная база + столбец tags рядом с открытым вопросом

# Параметры предобработки
MIN_TOKEN_LEN  <- 2          # минимальная длина токена (символов)
NORMALIZE_YO   <- TRUE       # заменять "ё" -> "е" перед лемматизацией

# =========================================================================
# ИСТОЧНИК ВЕКТОРОВ: "word2vec" (обучается на корпусе, шаг 03) или
# "llm" (локальные LLM-эмбеддинги через sentence-transformers, шаг 03b).
# LLM-вариант: высказывание эмбеддится целиком (учитывается порядок слов,
# отрицания, синтаксис), слова карты эмбеддятся той же моделью -- всё в одном
# векторном пространстве. Нужен Python 3 + пакет sentence-transformers.
# =========================================================================
EMBEDDING_SOURCE <- "llm"          # "word2vec" или "llm"
LLM_EMB_MODEL    <- "paraphrase-multilingual-mpnet-base-v2"
LLM_EMB_RDS      <- file.path(DATA_DIR, "03b_llm_embeddings.rds")
PYTHON_BIN       <- "python"

# Параметры word2vec
# Подобраны экспериментально под небольшой корпус (несколько тысяч коротких высказываний).
# На таком небольшом объёме данных cbow с dim=100 даёт вырожденное пространство
# (все косинусные близости ~0.99, т.е. векторы почти не различаются по направлению).
# skip-gram с меньшей размерностью и большим числом негативных примеров
# даёт гораздо более осмысленное разделение слов -- проверено на реальных данных.
W2V_DIM        <- 30
W2V_WINDOW     <- 5
W2V_MIN_COUNT  <- 4           # минимальная частота слова в корпусе, чтобы попасть в модель
W2V_ITER       <- 20
W2V_TYPE       <- "skip-gram" # "cbow" или "skip-gram"
W2V_NEGATIVE   <- 10

# Параметры t-SNE
TSNE_PERPLEXITY <- 15        # автоматически уменьшается, если словарь маленький
TSNE_SEED       <- 42

# Параметры карты слов / характерных высказываний
TOP_N_CHARACTERISTIC <- 5    # сколько высказываний показывать в подсказке при наведении
MIN_WORD_FREQ_ON_MAP <- 3    # в данные карты попадают слова с freq >= этого (жёсткий низ)
MIN_WORD_FREQ_DISPLAY <- 5   # фильтр отображения по умолчанию (регулируется в приложении)
MAX_WORDS_DISPLAY   <- 3000  # максимум слов на карте по умолчанию (регулируется в приложении)

# Перестроение карты по тегам
TAG_FEATURE_WEIGHT   <- 3    # вес близостей к тегам относительно исходных векторов в t-SNE
# Порог окраски слова в цвет тега зависит от источника векторов: у word2vec на
# малом корпусе близости сжаты к 1, у LLM-эмбеддингов распределены шире.
TAG_COLOR_SIMILARITY <- if (EMBEDDING_SOURCE == "llm") 0.45 else 0.60

# Файл с принудительными исключениями высказываний из тегов
TAG_EXCLUSIONS_CSV <- file.path(DATA_DIR, "tag_exclusions.csv")

# Порог косинусной близости по умолчанию для присвоения тега (регулируется в приложении).
# word2vec: на небольшом корпусе (~3500 коротких высказываний) близости сильно
# сжаты к верхней границе -- даже для случайного набора слов при пороге 0.5-0.6
# помечается 80-99% базы, поэтому порог высокий (0.85).
# llm: близости распределены шире, рабочий диапазон обычно 0.4-0.7.
# В приложении есть ползунок и живой предпросмотр -- подбирайте по нему.
DEFAULT_TAG_SIMILARITY_THRESHOLD <- if (EMBEDDING_SOURCE == "llm") 0.50 else 0.85

# =========================================================================
# Карта автотегов по сегментам (map/)
# =========================================================================
MAP_OUT_DIR <- "map/out"     # результаты с ответами респондентов; в репозиторий не попадают
MAP_K_FINE  <- 120           # мелких смысловых скоплений
MAP_K_MID   <- 36            # подтегов
MAP_K_TOP   <- 12            # тегов
MAP_LAMBDA  <- 3             # вес потери информации о сегменте при склейке (0 = только смысл)
MAP_W_SEG   <- 0.5           # вес предсказанных по тексту сегментов при мелкой кластеризации
